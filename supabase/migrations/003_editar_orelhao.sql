-- Edição dos dados do orelhão (posição, códigos e status), protegida pela mesma
-- senha de edição da migration 002. Cada alteração fica registrada no histórico.
-- Rode no SQL Editor do Supabase.

create table if not exists public.orelhoes_historico (
  id          bigint generated by default as identity primary key,
  orelhao_id  bigint not null references public.orelhoes (id) on delete cascade,
  antes       jsonb not null,
  depois      jsonb not null,
  alterado_em timestamptz not null default now()
);
alter table public.orelhoes_historico enable row level security;  -- sem policies: só o banco lê

create or replace function public.atualizar_orelhao(
  p_id bigint,
  p_senha text,
  p_lat double precision default null,      -- null = posição não mudou
  p_lng double precision default null,
  p_cod_localidade text default null,
  p_cod_ibge text default null,
  p_status text default null,
  p_cod_tup text default null
) returns boolean
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_antes jsonb;
begin
  if p_senha is distinct from (select value from public.app_config where key = 'edit_password') then
    return false;
  end if;
  if p_lat is not null and (p_lng is null or p_lat not between -35 and 6 or p_lng not between -75 and -32) then
    raise exception 'Coordenadas fora do Brasil';
  end if;

  select to_jsonb(o) - 'geom' into v_antes from public.orelhoes o where id = p_id;
  if v_antes is null then return false; end if;

  update public.orelhoes set
    cod_localidade = nullif(trim(p_cod_localidade), ''),
    cod_ibge       = nullif(trim(p_cod_ibge), ''),
    status         = nullif(trim(p_status), ''),
    cod_tup        = nullif(trim(p_cod_tup), ''),
    lat            = coalesce(p_lat, lat),
    lng            = coalesce(p_lng, lng),
    origem         = case when p_lat is not null then 'original' else origem end,
    origem_desc    = case when p_lat is not null then 'Posição corrigida manualmente' else origem_desc end
  where id = p_id;

  insert into public.orelhoes_historico (orelhao_id, antes, depois)
  select p_id, v_antes, to_jsonb(o) - 'geom' from public.orelhoes o where id = p_id;

  return true;
end $$;

revoke all on function public.atualizar_orelhao(bigint, text, double precision, double precision, text, text, text, text) from public;
grant execute on function public.atualizar_orelhao(bigint, text, double precision, double precision, text, text, text, text) to anon, authenticated;
