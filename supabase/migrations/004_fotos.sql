-- Fotos dos orelhões (para quando não há Street View / Google Earth).
-- Os arquivos ficam no Storage do Supabase (bucket "fotos", leitura pública).
-- Enviar e apagar exigem a senha de edição (migration 002). Como o app só tem a
-- chave pública, a senha libera uma autorização de 10 minutos para UM arquivo:
--   1. autorizar_foto(id, senha)      -> devolve um código (token)
--   2. o app envia o arquivo para fotos/<id>/<token>.jpg (o Storage confere o token)
--   3. registrar_foto(token, legenda) -> a foto passa a aparecer no app
-- Para apagar: apagar_foto(foto_id, senha) tira a foto do app e libera a remoção
-- do arquivo, que o app faz em seguida.
-- Rode no SQL Editor do Supabase.

-- Bucket público, só imagens, até 5 MB por arquivo
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fotos', 'fotos', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = true, file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.orelhoes_fotos (
  id          bigint generated by default as identity primary key,
  orelhao_id  bigint not null references public.orelhoes (id) on delete cascade,
  caminho     text not null unique,          -- caminho do arquivo no bucket "fotos"
  legenda     text,
  criado_em   timestamptz not null default now()
);
create index if not exists orelhoes_fotos_orelhao on public.orelhoes_fotos (orelhao_id);
alter table public.orelhoes_fotos enable row level security;
drop policy if exists "fotos: leitura pública" on public.orelhoes_fotos;
create policy "fotos: leitura pública" on public.orelhoes_fotos for select using (true);

-- Autorizações temporárias (sem policies: só as funções abaixo mexem)
create table if not exists public.fotos_autorizacoes (
  token       uuid primary key default gen_random_uuid(),
  orelhao_id  bigint,                 -- envio: orelhão do arquivo
  caminho     text,                   -- remoção: arquivo a apagar
  expira      timestamptz not null default now() + interval '10 minutes'
);
alter table public.fotos_autorizacoes enable row level security;

create or replace function public.autorizar_foto(p_id bigint, p_senha text) returns uuid
language plpgsql security definer set search_path = public as $$
declare v_token uuid;
begin
  if p_senha is distinct from (select value from public.app_config where key = 'edit_password') then return null; end if;
  if not exists (select 1 from public.orelhoes where id = p_id) then return null; end if;
  delete from public.fotos_autorizacoes where expira < now();
  insert into public.fotos_autorizacoes (orelhao_id) values (p_id) returning token into v_token;
  return v_token;
end $$;

-- Usada pela policy do Storage: o arquivo <id>/<token>.<ext> só entra com token válido
create or replace function public.foto_envio_permitido(p_caminho text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.fotos_autorizacoes a
    where a.orelhao_id is not null and a.expira > now()
      and p_caminho ~ '^[0-9]+/[0-9a-f-]{36}\.(jpg|png|webp)$'
      and a.orelhao_id::text = split_part(p_caminho, '/', 1)
      and a.token::text = split_part(split_part(p_caminho, '/', 2), '.', 1)
  )
$$;

create or replace function public.foto_remocao_permitida(p_caminho text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.fotos_autorizacoes where caminho = p_caminho and expira > now())
$$;

create or replace function public.registrar_foto(p_token uuid, p_caminho text, p_legenda text default null) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_orelhao bigint; v_id bigint;
begin
  select orelhao_id into v_orelhao from public.fotos_autorizacoes
  where token = p_token and orelhao_id is not null and expira > now();
  if v_orelhao is null or split_part(p_caminho, '/', 1) <> v_orelhao::text
     or split_part(split_part(p_caminho, '/', 2), '.', 1) <> p_token::text then return null; end if;
  if not exists (select 1 from storage.objects where bucket_id = 'fotos' and name = p_caminho) then return null; end if;
  insert into public.orelhoes_fotos (orelhao_id, caminho, legenda)
  values (v_orelhao, p_caminho, nullif(trim(p_legenda), '')) returning id into v_id;
  delete from public.fotos_autorizacoes where token = p_token;
  return v_id;
end $$;

-- Tira a foto do app e devolve o caminho do arquivo (liberado para remoção por 10 min)
create or replace function public.apagar_foto(p_foto_id bigint, p_senha text) returns text
language plpgsql security definer set search_path = public as $$
declare v_caminho text;
begin
  if p_senha is distinct from (select value from public.app_config where key = 'edit_password') then return null; end if;
  delete from public.orelhoes_fotos where id = p_foto_id returning caminho into v_caminho;
  if v_caminho is not null then insert into public.fotos_autorizacoes (caminho) values (v_caminho); end if;
  return v_caminho;
end $$;

revoke all on function public.autorizar_foto(bigint, text) from public;
revoke all on function public.registrar_foto(uuid, text, text) from public;
revoke all on function public.apagar_foto(bigint, text) from public;
revoke all on function public.foto_envio_permitido(text) from public;
revoke all on function public.foto_remocao_permitida(text) from public;
grant execute on function public.autorizar_foto(bigint, text) to anon, authenticated;
grant execute on function public.registrar_foto(uuid, text, text) to anon, authenticated;
grant execute on function public.apagar_foto(bigint, text) to anon, authenticated;
grant execute on function public.foto_envio_permitido(text) to anon, authenticated;
grant execute on function public.foto_remocao_permitida(text) to anon, authenticated;

-- Policies do Storage para o bucket "fotos"
drop policy if exists "fotos: ver" on storage.objects;
drop policy if exists "fotos: enviar com token" on storage.objects;
drop policy if exists "fotos: apagar liberado" on storage.objects;
create policy "fotos: ver" on storage.objects for select to anon, authenticated
  using (bucket_id = 'fotos');
create policy "fotos: enviar com token" on storage.objects for insert to anon, authenticated
  with check (bucket_id = 'fotos' and public.foto_envio_permitido(name));
create policy "fotos: apagar liberado" on storage.objects for delete to anon, authenticated
  using (bucket_id = 'fotos' and public.foto_remocao_permitida(name));
