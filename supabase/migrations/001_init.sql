-- Orelhão Digital — schema inicial
-- Rode no SQL Editor do Supabase (ou via MCP apply_migration)

create extension if not exists postgis;

create table if not exists public.orelhoes (
  id              bigint generated by default as identity primary key,
  localidade      text not null,
  regiao          text not null check (regiao in ('Norte','Nordeste','Centro-Oeste','Sudeste','Sul')),
  uf              char(2) not null,
  municipio       text not null,
  cod_localidade  text,
  cod_ibge        text,
  lat             double precision not null,
  lng             double precision not null,
  geom            geography(Point, 4326) generated always as (st_setsrid(st_makepoint(lng, lat), 4326)::geography) stored,
  origem          text not null default 'original' check (origem in ('original','estimada')),
  origem_desc     text,
  -- campos futuros (planilha complementar)
  cod_tup         text,
  status          text,
  rota            text,
  observacoes     text,
  extra           jsonb not null default '{}'::jsonb,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index if not exists orelhoes_uf_idx        on public.orelhoes (uf);
create index if not exists orelhoes_regiao_idx    on public.orelhoes (regiao);
create index if not exists orelhoes_municipio_idx on public.orelhoes (uf, municipio);
create index if not exists orelhoes_geom_idx      on public.orelhoes using gist (geom);

-- updated_at automático
create or replace function public.set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists orelhoes_updated_at on public.orelhoes;
create trigger orelhoes_updated_at before update on public.orelhoes
for each row execute function public.set_updated_at();

-- Orelhões mais próximos de um ponto
create or replace function public.orelhoes_proximos(p_lat double precision, p_lng double precision, p_limite int default 20)
returns table (id bigint, localidade text, municipio text, uf char(2), lat double precision, lng double precision, distancia_km double precision)
language sql stable set search_path = public, extensions as $$
  select o.id, o.localidade, o.municipio, o.uf, o.lat, o.lng,
         st_distance(o.geom, st_setsrid(st_makepoint(p_lng, p_lat), 4326)::geography) / 1000
  from public.orelhoes o
  order by o.geom <-> st_setsrid(st_makepoint(p_lng, p_lat), 4326)::geography
  limit p_limite
$$;

-- RLS: leitura pública, escrita só para usuários logados
alter table public.orelhoes enable row level security;

drop policy if exists "leitura publica" on public.orelhoes;
create policy "leitura publica" on public.orelhoes for select using (true);

drop policy if exists "escrita autenticada" on public.orelhoes;
create policy "escrita autenticada" on public.orelhoes for all
  to authenticated using (true) with check (true);
